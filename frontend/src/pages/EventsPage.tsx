import React, { useState, useMemo } from 'react';
import {
  Search,
  RotateCcw,
  ExternalLink,
  ShieldAlert,
  Info,
} from 'lucide-react';
import { SecurityEvent, EventStatus } from '../types';
import { StatusBadge } from '../components/ui/StatusBadge';
import { EventDetailModal } from '../components/dashboard/EventDetailModal';
import { EmptyState } from '../components/ui/EmptyState';

import { formatUtcTimestamp, formatConfidencePercent, safeLower } from '../utils/formatters';

interface EventsPageProps {
  events: SecurityEvent[];
  isLive: boolean;
  onRefresh: () => Promise<void>;
  initialSearchFilter?: string;
  highlightedEventIds?: Set<string>;
  onStatusChange?: (eventId: string, newStatus: EventStatus) => Promise<{ success: boolean; message: string; isLive: boolean }>;
}

type SortField = 'timestamp' | 'risk_score' | 'confidence';
type SortOrder = 'desc' | 'asc';

export const EventsPage: React.FC<EventsPageProps> = ({
  events,
  isLive,
  onRefresh,
  initialSearchFilter = '',
  highlightedEventIds,
  onStatusChange,
}) => {
  const [search, setSearch] = useState(initialSearchFilter);
  const [selectedRisk, setSelectedRisk] = useState<string>('ALL');
  const [selectedStatus, setSelectedStatus] = useState<string>('ALL');
  const [selectedType, setSelectedType] = useState<string>('ALL');
  const [sortField, setSortField] = useState<SortField>('timestamp');
  const [sortOrder, setSortOrder] = useState<SortOrder>('desc');
  const [selectedEvent, setSelectedEvent] = useState<SecurityEvent | null>(null);
  const [isRefreshing, setIsRefreshing] = useState(false);

  // Available filter options derived from dataset
  const eventTypes = useMemo(() => {
    const types = new Set<string>();
    events.forEach((e) => types.add(e.event_type));
    return Array.from(types);
  }, [events]);

  const filteredAndSortedEvents = useMemo(() => {
    return events
      .filter((evt) => {
        // Search filter
        if (search.trim()) {
          const q = search.toLowerCase();
          const matches =
            safeLower(evt.event_id).includes(q) ||
            safeLower(evt.camera_id).includes(q) ||
            safeLower(evt.event_type).includes(q) ||
            safeLower(evt.zone_id).includes(q) ||
            safeLower(evt.description).includes(q);
          if (!matches) return false;
        }

        // Risk filter
        if (selectedRisk !== 'ALL') {
          const level = evt.risk_level || evt.severity;
          if (level !== selectedRisk) return false;
        }

        // Status filter
        if (selectedStatus !== 'ALL') {
          if (evt.status !== selectedStatus) return false;
        }

        // Event Type filter
        if (selectedType !== 'ALL') {
          if (evt.event_type !== selectedType) return false;
        }

        return true;
      })
      .sort((a, b) => {
        let comp = 0;
        if (sortField === 'timestamp') {
          comp = new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime();
        } else if (sortField === 'risk_score') {
          comp = (b.risk_score ?? 0) - (a.risk_score ?? 0);
        } else if (sortField === 'confidence') {
          comp = b.confidence - a.confidence;
        }
        return sortOrder === 'desc' ? comp : -comp;
      });
  }, [events, search, selectedRisk, selectedStatus, selectedType, sortField, sortOrder]);

  const handleClearFilters = () => {
    setSearch('');
    setSelectedRisk('ALL');
    setSelectedStatus('ALL');
    setSelectedType('ALL');
    setSortField('timestamp');
    setSortOrder('desc');
  };

  const handleRefresh = async () => {
    setIsRefreshing(true);
    try {
      await onRefresh();
    } finally {
      setIsRefreshing(false);
    }
  };

  const hasActiveFilters =
    search.trim() !== '' ||
    selectedRisk !== 'ALL' ||
    selectedStatus !== 'ALL' ||
    selectedType !== 'ALL';

  return (
    <div className="dashboard-container">
      {/* Header */}
      <div className="dashboard-heading-block">
        <div className="heading-title-group">
          <h1>Security Incident Ledger</h1>
          <p>
            Audit log of restricted-zone incursions and perimeter alerts generated by SentinelAI Computer Vision.
          </p>
        </div>

        <div className="heading-actions">
          <button
            type="button"
            className="btn-secondary"
            onClick={handleRefresh}
            disabled={isRefreshing}
          >
            <RotateCcw size={13} className={isRefreshing ? 'spin-icon' : ''} />
            {isRefreshing ? 'Syncing...' : 'Sync Events'}
          </button>
        </div>
      </div>

      {/* Demo Notice Banner if offline */}
      {!isLive && (
        <div
          style={{
            backgroundColor: 'rgba(245, 158, 11, 0.08)',
            border: '1px solid rgba(245, 158, 11, 0.25)',
            borderRadius: 'var(--radius-sm)',
            padding: '10px 14px',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'space-between',
            fontSize: '12px',
            color: 'var(--color-warning)',
          }}
        >
          <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
            <Info size={15} />
            <span>
              <strong>Live Events Not Verified:</strong> The event request did not return an authorized live dataset. Displaying {events.length} fallback records, if any; these records are synthetic and must not be treated as real incidents.
            </span>
          </div>
          <span className="badge badge-warning">FALLBACK DATA</span>
        </div>
      )}

      {/* Filter and Control Bar */}
      <div
        className="card-base"
        style={{
          padding: 'var(--space-md)',
          display: 'flex',
          flexWrap: 'wrap',
          gap: 'var(--space-md)',
          alignItems: 'center',
          justifyContent: 'space-between',
        }}
      >
        {/* Search Input */}
        <div style={{ position: 'relative', minWidth: '260px', flex: '1' }}>
          <Search size={14} className="search-icon" aria-hidden="true" />
          <input
            type="search"
            placeholder="Filter by Event ID, Camera, Zone, Description..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            className="search-input"
            style={{ width: '100%' }}
            aria-label="Filter events"
          />
        </div>

        {/* Filter Dropdowns */}
        <div style={{ display: 'flex', alignItems: 'center', gap: 'var(--space-sm)', flexWrap: 'wrap' }}>
          {/* Risk Level */}
          <select
            value={selectedRisk}
            onChange={(e) => setSelectedRisk(e.target.value)}
            className="search-input"
            style={{ width: 'auto', padding: '6px 10px', fontSize: '11px' }}
            aria-label="Filter by Risk Level"
          >
            <option value="ALL">All Risk Levels</option>
            <option value="CRITICAL">Critical</option>
            <option value="HIGH">High</option>
            <option value="MEDIUM">Medium</option>
            <option value="LOW">Low</option>
          </select>

          {/* Status */}
          <select
            value={selectedStatus}
            onChange={(e) => setSelectedStatus(e.target.value)}
            className="search-input"
            style={{ width: 'auto', padding: '6px 10px', fontSize: '11px' }}
            aria-label="Filter by Status"
          >
            <option value="ALL">All Statuses</option>
            <option value="NEW">New</option>
            <option value="ACKNOWLEDGED">Acknowledged</option>
            <option value="RESOLVED">Resolved</option>
          </select>

          {/* Event Type */}
          <select
            value={selectedType}
            onChange={(e) => setSelectedType(e.target.value)}
            className="search-input"
            style={{ width: 'auto', padding: '6px 10px', fontSize: '11px' }}
            aria-label="Filter by Event Type"
          >
            <option value="ALL">All Event Types</option>
            {eventTypes.map((t) => (
              <option key={t} value={t}>{t}</option>
            ))}
          </select>

          {/* Sorting */}
          <select
            value={`${sortField}-${sortOrder}`}
            onChange={(e) => {
              const [f, o] = e.target.value.split('-') as [SortField, SortOrder];
              setSortField(f);
              setSortOrder(o);
            }}
            className="search-input"
            style={{ width: 'auto', padding: '6px 10px', fontSize: '11px' }}
            aria-label="Sort events by"
          >
            <option value="timestamp-desc">Timestamp (Newest First)</option>
            <option value="timestamp-asc">Timestamp (Oldest First)</option>
            <option value="risk_score-desc">Risk Score (High to Low)</option>
            <option value="confidence-desc">Confidence (High to Low)</option>
          </select>

          {/* Clear Filters */}
          {hasActiveFilters && (
            <button
              type="button"
              className="btn-secondary"
              onClick={handleClearFilters}
              style={{ padding: '6px 10px', fontSize: '11px', color: 'var(--color-critical)' }}
              title="Reset all filters"
            >
              Reset Filters
            </button>
          )}
        </div>
      </div>

      {/* Events Table Container */}
      <div className="card-base" style={{ padding: 'var(--space-md)' }}>
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '12px' }}>
          <span style={{ fontSize: '12px', color: 'var(--color-text-secondary)', fontWeight: 500 }}>
            Showing {filteredAndSortedEvents.length} of {events.length} security incidents
          </span>
          <span style={{ fontSize: '11px', color: 'var(--color-text-dim)', fontFamily: 'var(--font-mono)' }}>
            Contract: API_CONTRACT.md v1.0
          </span>
        </div>

        {filteredAndSortedEvents.length === 0 ? (
          <EmptyState
            icon={ShieldAlert}
            title="No Incidents Match Search Criteria"
            description="Adjust your search query, risk-level filters, or lifecycle status to display matching records."
            actionText="Clear All Filters"
            onAction={handleClearFilters}
          />
        ) : (
          <div className="events-table-container">
            <table className="events-table">
              <thead>
                <tr>
                  <th>Event ID</th>
                  <th>Camera ID</th>
                  <th>Event Type</th>
                  <th>Timestamp (UTC)</th>
                  <th>Person Count</th>
                  <th>Confidence</th>
                  <th>Risk Level</th>
                  <th>Status</th>
                  <th>Action</th>
                </tr>
              </thead>
              <tbody>
                {filteredAndSortedEvents.map((evt) => (
                  <tr
                    key={evt.event_id}
                    className={highlightedEventIds?.has(evt.event_id) ? 'event-row-new' : ''}
                    onClick={() => setSelectedEvent(evt)}
                  >
                    <td className="event-id-cell">
                      <span>{evt.event_id}</span>
                      {evt.is_demo && (
                        <span
                          style={{
                            marginLeft: '6px',
                            fontSize: '9px',
                            backgroundColor: 'var(--color-bg-subtle)',
                            color: 'var(--color-text-dim)',
                            padding: '1px 4px',
                            borderRadius: '2px',
                          }}
                        >
                          DEMO
                        </span>
                      )}
                    </td>
                    <td className="camera-cell">{evt.camera_id}</td>
                    <td>
                      <span style={{ fontFamily: 'var(--font-mono)', fontSize: '11px' }}>
                        {evt.event_type}
                      </span>
                    </td>
                    <td className="timestamp-cell">
                      {formatUtcTimestamp(evt.timestamp)}
                    </td>
                    <td>
                      <span style={{ fontFamily: 'var(--font-mono)', fontWeight: 600 }}>
                        {evt.person_count ?? evt.evidence.person_count ?? 1}
                      </span>
                    </td>
                    <td>
                      <span style={{ fontFamily: 'var(--font-mono)', color: 'var(--color-text-highlight)' }}>
                        {formatConfidencePercent(evt.confidence)}
                      </span>
                    </td>
                    <td>
                      <StatusBadge type="risk" value={evt.risk_level || evt.severity} />
                    </td>
                    <td>
                      <StatusBadge type="status" value={evt.status} />
                    </td>
                    <td>
                      <button
                        type="button"
                        className="btn-secondary"
                        style={{ padding: '3px 8px', fontSize: '11px' }}
                        onClick={(e) => {
                          e.stopPropagation();
                          setSelectedEvent(evt);
                        }}
                      >
                        <ExternalLink size={11} />
                        Inspect
                      </button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>

      {/* Incident Detail Modal */}
      <EventDetailModal
        event={selectedEvent}
        onClose={() => setSelectedEvent(null)}
        onStatusChange={onStatusChange}
      />
    </div>
  );
};
